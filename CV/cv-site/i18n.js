const LANG_STORAGE_KEY = "cv-lang";

function getStoredLang() {
  try {
    return localStorage.getItem(LANG_STORAGE_KEY);
  } catch (e) {
    return null;
  }
}

function storeLang(lang) {
  try {
    localStorage.setItem(LANG_STORAGE_KEY, lang);
  } catch (e) {
    /* ignore */
  }
}

function applyLang(lang) {
  const dict = I18N[lang] || I18N.en;

  document.documentElement.lang = lang;
  document.documentElement.dir = dict.dir;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) {
      el.innerHTML = dict[key];
    }
  });

  const year = new Date().getFullYear();
  const footerEl = document.getElementById("footerNote");
  if (footerEl) {
    footerEl.innerHTML = dict["footer.note"].replace("{year}", year);
  }

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.classList.toggle("is-active", btn.getAttribute("data-lang") === lang);
  });

  // restart the terminal typing effect in the new language
  if (typeof window.restartTypingEffect === "function") {
    window.restartTypingEffect(dict["terminal.typed"]);
  }

  storeLang(lang);
}

document.addEventListener("DOMContentLoaded", () => {
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => applyLang(btn.getAttribute("data-lang")));
  });

  const initialLang = getStoredLang() || "en";
  applyLang(initialLang);
});
